function ranks(arr: string[]) {
  const o: Record<string, string> = {};
  arr.forEach((name, i) => {
    o[`skill.rank.${i}`] = name;
  });
  return o;
}

function levels(skill: string, arr: string[]) {
  const o: Record<string, string> = {};
  arr.forEach((line, i) => {
    o[`skill.${skill}.lv.${i}`] = line;
  });
  return o;
}

