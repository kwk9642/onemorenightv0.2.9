const HTML_LANG: Record<Locale, string> = { zh: "zh-Hant", ja: "ja", en: "en", ko: "ko" };
const KEY = "ash-lang";
let locale: Locale = "zh";
const subs = new Set<() => void>();

function emit() {
  subs.forEach((fn) => fn());
}

export function getLocale(): Locale {
  return locale;
}

export function bootLocale() {
  if (typeof window === "undefined") return;
  try {
    const saved = localStorage.getItem(KEY);
    if (saved === "zh" || saved === "ja" || saved === "en" || saved === "ko") locale = saved;
    else {
      const n = (navigator.language || "zh").toLowerCase();
      if (n.startsWith("ja")) locale = "ja";
      else if (n.startsWith("ko")) locale = "ko";
      else if (n.startsWith("en")) locale = "en";
      else if (n.startsWith("zh")) locale = "zh";
    }
  } catch {
    /* private mode */
  }
  document.documentElement.lang = HTML_LANG[locale];
}

export function setLocale(id: Locale) {
  locale = id;
  try {
    localStorage.setItem(KEY, id);
  } catch {
    /* private mode */
  }
  if (typeof document !== "undefined") document.documentElement.lang = HTML_LANG[id];
  emit();
}

function subscribe(fn: () => void) {
  subs.add(fn);
  return () => {
    subs.delete(fn);
  };
}

function fill(s: string, vars?: Record<string, string | number>) {
  if (!vars) return s;
  let out = s;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}

export function t(key: string, vars?: Record<string, string | number>) {
  const table = DICT[locale] ?? DICT.zh;
  return fill(table[key] ?? DICT.zh[key] ?? key, vars);
}

export function useT() {
  useSyncExternalStore(subscribe, getLocale, () => "zh" as Locale);
  return t;
}

